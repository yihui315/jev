#!/usr/bin/env python
"""Generate ``fixtures/v1.1/replay_default.jsonl`` (the shipped demo recording).

WHY A TRACKED GENERATOR. The fixture is the default recording path of
``RecordReplayProvider``, so a zero-configuration run reads it. It carries two
sha256 digests that the loader RECOMPUTES and COMPARES, which means a hand-edited
fixture is not merely stale -- it is refused. Bytes on disk must therefore be a
function of code, not of whoever last opened the file in an editor.

Both digests are produced by ``record_replay.build_entry()``, the SAME function
the loader verifies with. There is no second implementation of the digest rule
anywhere, which is what makes "the recorder and the checker disagree" impossible
rather than merely unlikely.

Modes
-----
``--emit``   write the fixture (default)
``--check``  verify the committed fixture is byte-identical to a fresh
             generation

Usage
-----
    F:/jev/.venv/Scripts/python.exe tools/v1_1_make_replay_fixture.py
    F:/jev/.venv/Scripts/python.exe tools/v1_1_make_replay_fixture.py --check
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
if str(REPO / "packages") not in sys.path:
    sys.path.insert(0, str(REPO / "packages"))

from jcc_core.providers.record_replay import build_entry, write_recording  # noqa: E402
from jcc_core.schemas import AEPEnvelope, AgentName, Assessment  # noqa: E402

OUT = REPO / "fixtures" / "v1.1" / "replay_default.jsonl"

RECORDING_ID = "v1.1-demo-fixture"
CREATED_AT = "2026-09-27T00:00:00Z"
CAPTURED_BY = "v1.1 demo fixture"

HEADER = (
    "# v1.1 demo replay recording -- jcc-replay/2.\n"
    "# GENERATED by tools/v1_1_make_replay_fixture.py via\n"
    "# jcc_core.providers.record_replay.build_entry() + write_recording(), so both\n"
    "# digests come from the SAME implementation the loader verifies with.\n"
    "# Do not hand-edit: fixture_digest would not recompute and the provider\n"
    "# would refuse to load the file.\n"
)

#: One nominal capture and one stuck capture, so a demo can show two different
#: policy outcomes without inventing a second recording file.
_SIGNALS_OK = dict(
    meaningful_progress=True, worker_stuck=False, work_off_track=False,
    requirements_satisfied=True, needs_verification=False, ready_to_finish=True,
    needs_human=False,
)
_SIGNALS_STUCK = dict(_SIGNALS_OK, meaningful_progress=False, worker_stuck=True,
                      ready_to_finish=False)


def _envelope(session_id, event_id, delivery_id, evidence, timestamp=1700000000.0):
    return AEPEnvelope(
        version="aep/v0.1", event_id=event_id, delivery_id=delivery_id,
        session_id=session_id, agent="workbuddy", project="v1.1-demo",
        evidence=evidence, schema_ok=True, timestamp=timestamp,
    )


def _assessment(session_id, risk, band, signals):
    return Assessment(
        agent=AgentName.WORKBUDDY, session_id=session_id, timestamp=1700000000.0,
        model="jev-1.13.0", provider="real", probabilities={"risk": risk},
        risk_score=risk, band=band, needs_verify=False,
        escalate=False, pause=False, steer=False, retry=False, finished=False,
        raw={"signals": signals, "source": "fixture"}, confidence=None,
        confidence_kind="none", provider_verified=True,
        blocker_kind="NONE", blocker_reasons=[],
    )


def entries():
    return [
        build_entry(
            envelope=_envelope("demo-session", "demo-e1", "demo-d1", {"ok": True}),
            assessment=_assessment("demo-session", 0.42, "medium", _SIGNALS_OK),
            recording_id=RECORDING_ID, created_at=CREATED_AT,
            provider_source="fixture", captured_by=CAPTURED_BY,
        ),
        build_entry(
            envelope=_envelope("demo-session", "demo-e2", "demo-d2",
                               {"ok": True, "step": 2}, 1700000060.0),
            assessment=_assessment("demo-session", 0.71, "high", _SIGNALS_STUCK),
            recording_id=RECORDING_ID, created_at=CREATED_AT,
            provider_source="fixture", captured_by=CAPTURED_BY,
        ),
    ]


def render() -> str:
    import json
    body = "".join(json.dumps(e, sort_keys=True) + "\n" for e in entries())
    return HEADER + body


def main(argv) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.is_file():
            print(f"STALE: {OUT.relative_to(REPO)} is missing")
            return 1
        on_disk = OUT.read_text(encoding="utf-8")
        if on_disk != text:
            print(
                f"STALE: {OUT.relative_to(REPO)} differs from a fresh generation.\n"
                "  The fixture carries digests the loader recomputes and compares, "
                "so a hand-edited file is REFUSED at load. Re-run without --check."
            )
            return 1
        print("OK: the shipped fixture is byte-identical to a fresh generation.")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {OUT.relative_to(REPO)} ({len(text)} bytes, {len(entries())} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
